//! Every IPC command the frontend may call must also be granted in a Tauri
//! capability, otherwise the call fails at runtime with
//! `Command X not allowed by ACL`. This test keeps the two lists in sync.

#[test]
fn every_declared_command_is_granted_by_a_capability() {
    use crate::domain::shell::SHELL_COMMAND_NAMES;
    use crate::ipc::dto::{LIVE_DATA_COMMAND_NAMES, MEDIA_COMMAND_NAMES};

    let permissions = include_str!("../../permissions/foundation.toml");
    let autogenerated = [
        include_str!("../../permissions/autogenerated/app_bootstrap.toml"),
        include_str!("../../permissions/autogenerated/app_status.toml"),
        include_str!("../../permissions/autogenerated/config_get.toml"),
        include_str!("../../permissions/autogenerated/config_set.toml"),
        include_str!("../../permissions/autogenerated/path_revoke.toml"),
        include_str!("../../permissions/autogenerated/path_select.toml"),
    ]
    .join("\n");
    let granted = format!("{permissions}\n{autogenerated}");

    for (scope, names) in [
        ("shell", SHELL_COMMAND_NAMES),
        ("live-data", LIVE_DATA_COMMAND_NAMES),
        ("media", MEDIA_COMMAND_NAMES),
    ] {
        for name in names {
            assert!(
                granted.contains(&format!("\"{name}\"")),
                "{scope} command `{name}` is not granted by any Tauri capability"
            );
        }
    }
}
